/** Which way is good for a figure: up (more savers), down (fewer cancellations) or neither. */
export type Better = "up" | "down" | "neither";

/** The change as the tile shows it: relative for amounts and counts, in points for shares. */
export function describeChange(
  change: Change<string | number | null>,
  kind: "relative" | "points" = "relative",
): { text: string; direction: -1 | 0 | 1 } | null {
  if (change.value === null || change.previous === null) return null;
  const now = Number(change.value);
  const before = Number(change.previous);
  const diff = now - before;
  const direction = diff > 0 ? 1 : diff < 0 ? -1 : 0;
  const arrow = direction > 0 ? "▲" : direction < 0 ? "▼" : "■";
  if (kind === "points") {
    return { text: `${arrow} ${Math.abs(diff * 100).toFixed(1)} pts`, direction };
  }
  if (before === 0)
    return now === 0 ? { text: "■ no change", direction: 0 } : { text: `${arrow} new`, direction };
  const pct = (diff / Math.abs(before)) * 100;
  return {
    text: `${arrow} ${Math.abs(pct) >= 100 ? Math.round(Math.abs(pct)) : Math.abs(pct).toFixed(1)}%`,
    direction,
  };
}

/**
 * One headline figure: its value, its change against the previous period of the same length,
 * a one-line definition and, where there is one, a link to the rows behind it.
 */
export function Tile({
  label,
  value,
  change,
  better = "up",
  definition,
  note,
  href,
}: {
  label: string;
  value: ReactNode;
  change?: { text: string; direction: -1 | 0 | 1 } | null;
  better?: Better;
  definition: string;
  note?: ReactNode;
  href?: string;
}) {
  const good =
    !change || change.direction === 0 || better === "neither"
      ? "text-ink-soft"
      : change.direction > 0 === (better === "up")
        ? "text-ok"
        : "text-bad";
  const body = (
    <>
      <p className="flex items-center gap-1.5 text-xs font-medium uppercase tracking-wide text-ink-faint">
        {label}
        <span className="group relative normal-case tracking-normal">
          <span
            tabIndex={0}
            aria-label={`What is ${label.toLowerCase()}?`}
            className="inline-flex h-4 w-4 cursor-help items-center justify-center rounded-full border border-line text-[10px] text-ink-faint"
          >
            ?
          </span>
          <span
            role="tooltip"
            className="pointer-events-none absolute left-1/2 top-6 z-20 hidden w-60 -translate-x-1/2 rounded-[var(--radius-control)] border border-line bg-surface px-3 py-2 text-xs font-normal text-ink-soft shadow-sm group-focus-within:block group-hover:block"
          >
            {definition}
          </span>
        </span>
      </p>
      <p className="mt-2 text-2xl font-semibold tabular-nums text-ink">{value}</p>
      <p className="mt-1 flex flex-wrap items-baseline gap-x-2 text-xs">
        {change ? (
          <span className={`font-medium ${good}`}>
            {change.text}
            <span className="sr-only"> against the previous period</span>
          </span>
        ) : change === null ? (
          <span className="text-ink-faint">no comparison</span>
        ) : null}
        {note ? <span className="text-ink-soft">{note}</span> : null}
      </p>
    </>
  );
  const box = "block rounded-[var(--radius-card)] border border-line bg-surface p-5";
  return href ? (
    <Link href={href} className={`${box} transition hover:border-navy`}>
      {body}
    </Link>
  ) : (
    <div className={box}>{body}</div>
  );
}
